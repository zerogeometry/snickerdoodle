// The Christmas sticker family: from the traced doodles in public/stickers/christmas/<id>.svg (what the
// Studio tray and canvas load — scripts/stickers/doodle_trace.py writes them) to the server's copy the
// print renderer draws (src/lib/stickers/christmas-art.ts, byte-identical, so preview == print) and a
// contact sheet for review (mockups/christmas/stickers-contact-sheet.png).
//
//   node scripts/stickers/build-art.mjs
//
// Rules the doodles keep: a child's felt-tip look (wobbly cocoa line, lopsided shapes, flat colour),
// brand-token colours only, a square 200 view box with the art centred and even padding, no die-cut
// border or shadow (founder, 26 Oct), nothing but <path>s (no ids, nothing external).
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');

// drawer order — the same list as STICKER_IDS in src/lib/stickers/index.ts (a test holds them equal)
export const ORDER = ['gingerbread', 'reindeer', 'snowman', 'santa', 'mrsClaus', 'penguin', 'star', 'holly', 'candyCane', 'tinsel', 'sack', 'present'];
const dir = path.join(root, 'public/stickers/christmas');
const S = Object.fromEntries(ORDER.map((id) => [id, readFileSync(path.join(dir, `${id}.svg`), 'utf8').trim()]));

const mod =
  `// GENERATED by scripts/stickers/build-art.mjs from public/stickers/christmas/*.svg — do not edit by hand.\n` +
  `// The print renderer draws these exact strings; the Studio loads the same files (preview == print).\n\n` +
  `import type { StickerId } from './index';\n\n` +
  `export const CHRISTMAS_STICKER_SVG: Record<StickerId, string> = {\n${ORDER.map((id) => `  ${id}:\n    '${S[id].replace(/\\/g, '\\\\').replace(/'/g, "\\'")}',`).join('\n')}\n};\n`;
writeFileSync(path.join(root, 'src/lib/stickers/christmas-art.ts'), mod);

// ── contact sheet: kraft, white and a dark tee ──
const require = createRequire(path.join(root, 'package.json'));
const { Resvg } = require('@resvg/resvg-js');
const cell = 220, cols = 4, rows = 3, band = cell * cols;
const grounds = [
  ['kraft', '#d9b98c'],
  ['white', '#ffffff'],
  ['dark tee', '#2b2118'],
];
let body = '';
grounds.forEach(([name, bg], g) => {
  const ox = g * (band + 20);
  body += `<rect x="${ox}" y="0" width="${band}" height="${cell * rows + 40}" fill="${bg}"/>`;
  body += `<text x="${ox + 16}" y="28" font-family="sans-serif" font-size="18" font-weight="700" fill="${g === 2 ? '#fffbf2' : '#2b2118'}">${name}</text>`;
  ORDER.forEach((id, i) => {
    const x = ox + (i % cols) * cell + 10, y = 40 + Math.floor(i / cols) * cell;
    const inner = S[id].replace(/^<svg[^>]*>/, '').replace(/<\/svg>$/, '');
    body += `<svg x="${x}" y="${y}" width="200" height="200" viewBox="0 0 200 200">${inner}</svg>`;
  });
});
const W = grounds.length * (band + 20) - 20, H = cell * rows + 40;
const sheet = `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}">${body}</svg>`;
mkdirSync(path.join(root, 'mockups/christmas'), { recursive: true });
writeFileSync(path.join(root, 'mockups/christmas/stickers-contact-sheet.png'), new Resvg(sheet, { font: { loadSystemFonts: true } }).render().asPng());
console.log('wrote', ORDER.length, 'stickers');
