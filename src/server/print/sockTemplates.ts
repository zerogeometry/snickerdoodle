/**
 * PRODIGI'S SOCK TEMPLATES (the ankle- and tube-sock template packs; .prodigi-assets/templates): each is
 * "both sides of ONE sock — the design will be the same for the pair". The print file's LEFT half is one
 * side of the sock, its RIGHT half the other side — the mirror image (the ankle sock's heel is on the
 * left in the left half, on the right in the right half; the file's middle line is the front of the sock,
 * its two outer edges meet at the back). Traced off the templates on 16 Nov 2026, as the DESIGN canvas
 * stands (the tube sock upright, cuff at the top — the way Prodigi's live print area stands too, so it is never turned),
 * for the LEFT half; the right half is its mirror. Rows run top to bottom, each [left, right] as fractions
 * of the half's width (null = nothing in that row):
 *  - `outline`: the sock's outline (heel and toe included; the template's own instruction text inside it
 *    counts as sock) — where the preview lays each side;
 *  - `lane`: where a drawing may go — the clear part of the sock (no heel or toe patch), kept
 *    SOCK_SAFE_MM inside the outline and the patches, so no drawing runs over an edge, a seam or the
 *    heel (founder, 16 Nov 2026: "not overlapping the edges of the print map, because it won't print
 *    properly"). The sock repeat (pattern-geometry sockLayout) lines drawings up along it.
 */
export interface SockSide {
  /** the half of the print file one side fills, in mm (the design canvas, upright) */
  halfMm: { w: number; h: number };
  outline: ReadonlyArray<readonly [number, number] | null>;
  lane: ReadonlyArray<readonly [number, number] | null>;
}

