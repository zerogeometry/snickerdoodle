/** ankle: 30 × 30 cm (prodigi-socks-ankle.png, 3543 px square) · tube: 30 × 52 cm upright (prodigi-socks-tube.png). */
export const SOCK_SIDES = {
  ankle: { halfMm: { w: 150, h: 300 }, ...ANKLE },
  tube: { halfMm: { w: 150, h: 520 }, ...TUBE },
} as const satisfies Record<string, SockSide>;

/** The sock whose template a print canvas is (its size in mm, the design canvas upright), or null. */
export function sockSideFor(canvas: { width: number; height: number }, dpi: number): SockSide | null {
  const w = (canvas.width / dpi) * 25.4, h = (canvas.height / dpi) * 25.4;
  for (const s of Object.values(SOCK_SIDES)) if (Math.abs(w - 2 * s.halfMm.w) < 3 && Math.abs(h - s.halfMm.h) < 3) return s;
  return null;
}
